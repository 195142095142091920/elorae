/* uo1 (2026-11-04): where each image is used ("Used on" in the Gallery details).
   edit/media/usage.json = { pages: { "<site url>": { t: "<page title>", u: { "<image path>": ["hero"|"art"|"card"|"inline"|"background"|"image", ...] } } } }
   - tools/build-media-usage.js writes it for the whole site (node, this file's pure helpers).
   - core.js commitFiles() updates it in the same commit whenever an editor save writes or deletes
     an .html page, so it stays right after edit-mode saves.
   Image paths are repo paths (assets/..., edit/media/files/...), as in edit/media/catalog.json.
   Kinds: hero = .art-hero image; art = Art strip thumbnail (.art-swap-thumbs [data-src]);
   card = Index card; inline = a figure / image in the page body; background = CSS url(). */
(function (root) {
  "use strict";
  var PATH = "edit/media/usage.json";
  var VOID = { img: 1, meta: 1, link: 1, br: 1, hr: 1, source: 1, input: 1, wbr: 1, area: 1, base: 1, col: 1, embed: 1, track: 1 };
  function attr(tag, name) { var m = new RegExp("\\s" + name + "\\s*=\\s*(\"([^\"]*)\"|'([^']*)')", "i").exec(tag); return m ? (m[2] != null ? m[2] : m[3]) : null; }
  function hasClass(tag, c) { return (" " + (attr(tag, "class") || "") + " ").indexOf(" " + c + " ") >= 0; }
  function unent(s) { return String(s).replace(/&amp;/g, "&").replace(/&quot;/g, '"').replace(/&#39;|&#x27;/g, "'"); }
  // "/cdn-cgi/image/w=..,onerror=redirect/assets/A%20B.png?v=1" -> "assets/A B.png"; else null.
  function norm(u) {
    if (!u) return null;
    u = unent(String(u).trim()).replace(/^url\(\s*['"]?|['"]?\s*\)$/g, "");
    u = u.replace(/^https?:\/\/(www\.)?elorae\.world/i, "").replace(/[?#].*$/, "");
    try { u = decodeURIComponent(u); } catch (e) {}
    u = u.replace(/^\/+/, "").replace(/^cdn-cgi\/image\/[^\/]*\//, "");
    return /^(assets|edit\/media\/files)\//.test(u) ? u : null;
  }
  function pageUrl(path) {
    var p = String(path).replace(/^\/+/, "");
    if (p === "index.html") return "/";
    var m = /^(.*)\/index\.html$/.exec(p); if (m) return "/" + m[1] + "/";
    m = /^(.*)\.html$/.exec(p); return m ? "/" + m[1] + "/" : null;
  }
  function titleOf(html) {
    var m = /<title[^>]*>([\s\S]*?)<\/title>/i.exec(html || "");
    var t = m ? unent(m[1]).replace(/\s+/g, " ").trim().replace(/\s*[-\u2013\u2014\u00b7|]\s*Elorae$/i, "") : "";
    return t || "Elorae";
  }
  // One page -> { "<image path>": [kinds] }.
  function scan(html) {
    var out = {}, stack = [], re = /<(\/?)([a-z][a-z0-9-]*)\b([^>]*)>|<!--[\s\S]*?-->/gi, m;
    function add(u, kind) { var p = norm(u); if (!p) return; var k = out[p] || (out[p] = []); if (k.indexOf(kind) < 0) k.push(kind); }
    function inside(fn) { for (var i = stack.length - 1; i >= 0; i--) if (fn(stack[i])) return true; return false; }
    html = String(html || "").replace(/<(script|style)\b[\s\S]*?<\/\1>/gi, "");
    while ((m = re.exec(html))) {
      if (!m[2]) continue;
      var close = m[1], name = m[2].toLowerCase(), tag = m[0];
      if (close) { for (var j = stack.length - 1; j >= 0; j--) if (stack[j].n === name) { stack.length = j; break; } continue; }
      if (name === "meta" || name === "link") continue;
      var refs = [];
      ["src", "data-src", "poster", "data-full"].forEach(function (a) { var v = attr(tag, a); if (v) refs.push(v); });
      var ss = attr(tag, "srcset"); if (ss) ss.split(",").forEach(function (c) { var u = c.trim().split(/\s+/)[0]; if (u) refs.push(u); });
      var kind = null;
      if (refs.length) {
        if (inside(function (e) { return e.thumbs; }) && attr(tag, "data-src")) kind = "art";
        else if (inside(function (e) { return e.hero; })) kind = "hero";
        else if (inside(function (e) { return e.card; })) kind = "card";
        else if (inside(function (e) { return e.fig || e.main; })) kind = "inline";
        else kind = "image";
        refs.forEach(function (u) { add(u, kind); });
      }
      var st = attr(tag, "style"), um, ure = /url\(\s*(['"]?)([^'")]+)\1\s*\)/gi;
      if (st) while ((um = ure.exec(unent(st)))) add(um[2], hasClass(tag, "index-card") || inside(function (e) { return e.card; }) ? "card" : "background");
      if (!VOID[name] && !/\/\s*$/.test(tag)) stack.push({ n: name, hero: hasClass(tag, "art-hero"), card: hasClass(tag, "index-card"), thumbs: hasClass(tag, "art-swap-thumbs"),
        fig: name === "figure", main: name === "main" });
    }
    return out;
  }
  function empty() { return { _readme: "Where each image is used (Gallery \u2018Used on\u2019). Generated by tools/build-media-usage.js; edit-mode saves update the pages they write (edit/usage.js).", version: 1, pages: {} }; }
  // Apply written / deleted pages: files [{ path, text } | { path, delete: true }] -> new JSON text (or null when unchanged).
  function update(text, files) {
    var o; try { o = text ? JSON.parse(text) : empty(); } catch (e) { return null; }
    o.pages = o.pages || {};
    var before = JSON.stringify(o.pages), seen = {};
    (files || []).forEach(function (f) {
      if (!f || !/\.html$/.test(f.path) || /^(edit|tools|docs|_verify|scripts)\//.test(f.path) || /^search(\.html|\/)/.test(f.path)) return; // search: a derived listing
      var url = pageUrl(f.path); if (!url) return;
      if (f.delete) { if (!seen[url]) delete o.pages[url]; return; }
      if (f.binary || typeof f.text !== "string") return;
      seen[url] = 1;
      var u = scan(f.text);
      if (Object.keys(u).length) o.pages[url] = { t: titleOf(f.text), u: u }; else delete o.pages[url];
    });
    var keys = Object.keys(o.pages).sort(), sorted = {};
    keys.forEach(function (k) { sorted[k] = o.pages[k]; }); o.pages = sorted;
    return JSON.stringify(o.pages) === before ? null : JSON.stringify(o, null, 1) + "\n";
  }
  // Image path -> [{ url, title, kinds }] (title A-Z).
  function usesOf(o, path) {
    var out = [], pages = (o && o.pages) || {};
    Object.keys(pages).forEach(function (url) { var k = pages[url].u && pages[url].u[path]; if (k) out.push({ url: url, title: pages[url].t || url, kinds: k }); });
    return out.sort(function (a, b) { return a.title.localeCompare(b.title); });
  }
  var api = { PATH: PATH, scan: scan, norm: norm, pageUrl: pageUrl, titleOf: titleOf, update: update, usesOf: usesOf, empty: empty };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  if (root) root.EloraeUsage = api;
})(typeof window !== "undefined" ? window : null);
